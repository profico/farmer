import { FARMER_LOGO_SVG } from "./farmer-logo";
import { compileTypstPdf } from "./typst";

// Data is fully pre-formatted here — the Typst template only does layout.
// Numbers cross the boundary only where the template draws with them (bars),
// plus boolean flags where the design colors by data semantics (over-budget,
// zero values).
//
// This report is hours-only. There is deliberately no revenue, cost or margin
// anywhere in it: rates do not exist in this system, so any money figure would
// be invented. A EUR budget is the single exception and appears only as an
// unmodified label beside the hour figures, never as an input to arithmetic.
export type ReportPdfStat = {
	value: string;
	unit: string | null;
};

export type ReportPdfData = {
	orgName: string;
	periodLabel: string; // "June 2026" (masthead)
	periodShortLabel: string; // "Jun 2026" (running header)
	generatedLabel: string;
	memberCountLabel: string; // "9 members"
	summary: {
		final: ReportPdfStat;
		expected: ReportPdfStat;
		utilization: ReportPdfStat;
		activeProjects: ReportPdfStat;
	};
	utilization: {
		name: string;
		typeLabel: string; // "Billable" / "Contractor"
		expected: string;
		final: string;
		finalIsZero: boolean;
		pct: number | null;
	}[];
	budgets: {
		name: string;
		clientName: string;
		hours: string;
		budget: string | null;
		budgetAmount: string | null;
		remaining: string | null;
		remainingNegative: boolean;
		pct: number | null;
	}[];
};

// The number formatting lives in `report-format.ts`, which the reports screen
// and the CSV export import as well — this module cannot be imported from a
// route, because `./typst` above binds a native compiler. Re-exported here so
// the PDF pipeline still has one import.
export {
	formatHoursLabel,
	formatMonthLabel,
	formatMonthShortLabel,
	formatWholeHoursValue,
} from "./report-format";

// Implements the approved "Time Report.dc.html" mockup from the Claude Design
// project: warm near-black ink, violet brand accents, amber for overtime, red
// for budget overrun. Geist sans carries all figures (tabular numerals); Geist
// Mono only the micro uppercase labels and running header/footer meta. All
// faces are embedded via fontBlobs in typst.ts. Sizes are the mockup's px
// values × 0.75 (CSS px → pt).
const TEMPLATE = `
#let data = json(bytes(sys.inputs.data))

#let ink = rgb("#26232b")
#let secondary = rgb("#79747f")
#let muted = rgb("#a8a3ad")
#let dot = rgb("#c9c4cd")
#let hairline = rgb("#e7e3e8")
#let hairline2 = rgb("#efece8")
#let violet = rgb("#6a45c8")
#let violet-bar = rgb("#7b54d6")
#let violet-light = rgb("#b59be8")
#let amber = rgb("#d98a2b")
#let amber-track = rgb("#f6ecda")
#let amber-text = rgb("#9a6a1c")
#let neg = rgb("#c0392b")
#let pos = rgb("#2f6f47")
#let pos-light = rgb("#4fa36b")

#let sans = "Geist"
#let mono = "Geist Mono"

#let mlabel(body, size: 6pt, fill: muted, track: 0.08em, weight: "semibold") = text(
  font: mono, size: size, weight: weight, tracking: track, fill: fill, upper(body),
)
#let num(body, size: 9pt, fill: ink, weight: "regular") = text(
  font: sans, size: size, fill: fill, weight: weight,
  number-width: "tabular", tracking: -0.01em, body,
)

#set page(
  paper: "a4",
  margin: (x: 36pt, top: 48pt, bottom: 54pt),
  // Running header from page 2 on — page 1 opens with the masthead instead.
  header: context if counter(page).get().first() > 1 {
    grid(
      columns: (1fr, auto),
      align: (left + horizon, right + horizon),
      text(size: 7.5pt, weight: "semibold", fill: secondary)[Time report#h(4.5pt)#text(fill: dot)[·]#h(4.5pt)#data.orgName],
      text(font: mono, size: 7pt, weight: "medium", fill: muted, tracking: 0.02em, data.periodShortLabel),
    )
    v(4.5pt)
    line(length: 100%, stroke: 0.75pt + hairline)
  },
  footer: context {
    line(length: 100%, stroke: 0.75pt + hairline)
    v(4.5pt)
    grid(
      columns: (1fr, auto),
      text(font: mono, size: 6.75pt, weight: "medium", fill: muted)[Generated by Farmer · #data.generatedLabel],
      text(font: mono, size: 6.75pt, weight: "medium", fill: muted, counter(page).display("1 / 1", both: true)),
    )
  },
)
#set text(font: sans, size: 9pt, fill: ink)

#let sec-rule = line(length: 100%, stroke: 0.75pt + hairline2)
#let h2(body) = text(size: 9.75pt, weight: "semibold", fill: ink, body)

// ── Masthead ────────────────────────────────────────────────────────────────
#grid(
  columns: (auto, 1fr),
  align: (left + horizon, right + horizon),
  grid(
    columns: (auto, auto),
    column-gutter: 9pt,
    align: (horizon, horizon),
    image(bytes(sys.inputs.logo), format: "svg", height: 27pt),
    stack(
      spacing: 3pt,
      mlabel("Time report", size: 6.5pt, fill: violet, track: 0.15em),
      text(size: 18pt, weight: "semibold", tracking: -0.01em, data.orgName),
    ),
  ),
  stack(
    spacing: 3pt,
    align(right, mlabel("Period", track: 0.11em)),
    align(right, text(size: 9pt, weight: "semibold", data.periodLabel)),
  ),
)
#v(15pt)

// ── Summary ─────────────────────────────────────────────────────────────────
#grid(
  columns: (auto, 1fr),
  column-gutter: 6.75pt,
  align: (left + horizon, horizon),
  h2[Summary],
  sec-rule,
)
#v(6.75pt)
#let stat(label, s, vfill: ink, ufill: muted) = stack(
  spacing: 5.25pt,
  mlabel(label, fill: secondary, track: 0.09em),
  box[#num(s.value, size: 19.5pt, fill: vfill, weight: "semibold")#if s.unit != none [#num(s.unit, size: 11.25pt, fill: ufill, weight: "medium")]],
)
#block(
  width: 100%,
  stroke: 0.75pt + hairline,
  radius: 7.5pt,
  clip: true,
  table(
    columns: (1fr, 1fr, 1fr, 1fr),
    stroke: (x, y) => if x > 0 { (left: 0.75pt + hairline) },
    inset: (x: 10.5pt, y: 8.25pt),
    stat("Final hours", data.summary.final),
    stat("Expected hours", data.summary.expected),
    stat(
      "Utilization",
      data.summary.utilization,
      vfill: if data.summary.utilization.unit == none { muted } else { violet },
      ufill: violet-light,
    ),
    stat("Active projects", data.summary.activeProjects),
  ),
)
#v(18pt)

// ── Team utilization ────────────────────────────────────────────────────────
#grid(
  columns: (auto, 1fr, auto),
  column-gutter: 6.75pt,
  align: (left + horizon, horizon, right + horizon),
  h2[Team utilization],
  sec-rule,
  text(size: 7.5pt, weight: "medium", fill: muted, data.memberCountLabel),
)
#v(6pt)
#let th(body, al: left) = table.cell(align: al + horizon, mlabel(body))
#let util-cell(r) = if r.pct == none {
  grid(
    columns: (1fr, 25.5pt),
    column-gutter: 6.75pt,
    align: (left + horizon, right + horizon),
    text(size: 7pt, style: "italic", fill: muted)[No expected hours],
    num("—", size: 8.5pt, fill: muted),
  )
} else {
  let over = r.pct > 100
  let p = calc.min(calc.max(r.pct, 0), 100)
  grid(
    columns: (1fr, 25.5pt),
    column-gutter: 6.75pt,
    align: (left + horizon, right + horizon),
    box(
      width: 100%, height: 3.75pt, radius: 2.25pt, clip: true,
      fill: if over { amber-track } else { hairline2 },
      box(width: p * 1%, height: 100%, radius: 2.25pt, fill: if over { amber } else { violet-bar }),
    ),
    num(
      str(r.pct) + "%", size: 8.5pt,
      fill: if over { amber-text } else if r.pct == 0 { muted } else { ink },
      weight: if over { "semibold" } else if r.pct == 0 { "regular" } else { "medium" },
    ),
  )
}
#let subline(body, fill: muted) = text(
  size: 6.75pt, fill: fill, number-width: "tabular", body,
)
#if data.utilization.len() == 0 [
  #text(size: 8.25pt, fill: muted)[No members in this period.]
] else [
  #let n = data.utilization.len()
  #table(
    columns: (1fr, 56pt, 64pt, 138pt),
    align: (left + horizon, right + horizon, right + horizon, left + horizon),
    stroke: (x, y) => if y == 0 { (bottom: 0.75pt + hairline) } else if y < n { (bottom: 0.75pt + hairline2) },
    inset: (x, y) => (
      left: if x == 0 { 0pt } else if x == 3 { 10.5pt } else { 7.5pt },
      right: if x == 3 { 0pt } else { 7.5pt },
      top: if y == 0 { 0pt } else { 5.25pt },
      bottom: if y == 0 { 4.5pt } else { 5.25pt },
    ),
    table.header(
      th("Member"),
      th("Expected", al: right),
      th("Final", al: right),
      th("Utilization"),
    ),
    ..data.utilization.map(r => (
      [
        #text(size: 8.25pt, weight: "semibold", r.name)
        #linebreak()#subline(r.typeLabel)
      ],
      if r.pct == none { num("—", fill: muted) } else { num(r.expected, fill: secondary) },
      num(r.final, fill: if r.finalIsZero { muted } else { ink }),
      util-cell(r),
    )).flatten(),
  )
]
#v(18pt)

// ── Fixed-scope budget burn ─────────────────────────────────────────────────
// Hours against hours. Where a project also carries a monetary budget it is
// printed verbatim as a subline for context — nothing is computed from it.
#grid(
  columns: (auto, auto, 1fr),
  column-gutter: 6.75pt,
  align: (left + horizon, left + horizon, horizon),
  h2[Fixed-scope budget burn],
  mlabel("All-time", size: 6.75pt, track: 0.06em, weight: "medium"),
  sec-rule,
)
#v(6pt)
#let burn-cell(r) = if r.pct == none {
  grid(
    columns: (1fr, 25.5pt),
    column-gutter: 6.75pt,
    align: (left + horizon, right + horizon),
    text(size: 7pt, style: "italic", fill: muted)[No hour budget],
    num("—", size: 8.5pt, fill: muted),
  )
} else {
  let over = r.pct > 100
  let p = calc.min(calc.max(r.pct, 0), 100)
  grid(
    columns: (1fr, 25.5pt),
    column-gutter: 6.75pt,
    align: (left + horizon, right + horizon),
    box(
      width: 100%, height: 3.75pt, radius: 2.25pt, clip: true,
      fill: if over { amber-track } else { hairline2 },
      box(width: p * 1%, height: 100%, radius: 2.25pt, fill: if over { neg } else { violet-bar }),
    ),
    num(
      str(r.pct) + "%", size: 8.5pt,
      fill: if over { neg } else if r.pct == 0 { muted } else { ink },
      weight: if over { "semibold" } else if r.pct == 0 { "regular" } else { "medium" },
    ),
  )
}
#if data.budgets.len() == 0 [
  #text(size: 8.25pt, fill: muted)[No active fixed-scope projects.]
] else [
  #let n = data.budgets.len()
  #table(
    columns: (1fr, 64pt, 64pt, 64pt, 126pt),
    align: (left + horizon, right + horizon, right + horizon, right + horizon, left + horizon),
    stroke: (x, y) => if y == 0 { (bottom: 0.75pt + hairline) } else if y < n { (bottom: 0.75pt + hairline2) },
    inset: (x, y) => (
      left: if x == 0 { 0pt } else if x == 4 { 10.5pt } else { 7.5pt },
      right: if x == 4 { 0pt } else { 7.5pt },
      top: if y == 0 { 0pt } else { 6pt },
      bottom: if y == 0 { 4.5pt } else { 6pt },
    ),
    table.header(
      th("Project"),
      th("Logged", al: right),
      th("Budget", al: right),
      th("Remaining", al: right),
      th("Burn"),
    ),
    ..data.budgets.map(r => (
      [
        #text(size: 8.25pt, weight: "semibold", r.name)
        #linebreak()#subline(r.clientName)
      ],
      num(r.hours),
      [
        #if r.budget == none { num("—", fill: muted) } else { num(r.budget, fill: secondary) }
        #if r.budgetAmount != none [#linebreak()#subline(r.budgetAmount)]
      ],
      if r.remaining == none { num("—", fill: muted) } else {
        num(r.remaining, fill: if r.remainingNegative { neg } else { pos })
      },
      burn-cell(r),
    )).flatten(),
  )
]
`;

export const renderReportPdf = (data: ReportPdfData): Buffer =>
	compileTypstPdf(TEMPLATE, {
		data: JSON.stringify(data),
		logo: FARMER_LOGO_SVG,
	});
