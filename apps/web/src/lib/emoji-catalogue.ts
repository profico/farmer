// The project icon picker's catalogue: a slice of the emoji set, grouped the
// way the Mac's picker groups it, each with the words people search by. A
// slice on purpose — the full Unicode list is three thousand entries and a
// dependency, and a project wants one of a few hundred recognisable marks,
// not a flag for every country. Add to a category when somebody asks.

export type CatalogueEmoji = { char: string; name: string };
export type EmojiCategory = {
	id: string;
	label: string;
	/** The emoji that stands for the category in the picker's row. */
	glyph: string;
	emoji: CatalogueEmoji[];
};

const cat = (
	id: string,
	label: string,
	glyph: string,
	pairs: [string, string][],
): EmojiCategory => ({
	id,
	label,
	glyph,
	emoji: pairs.map(([char, name]) => ({ char, name })),
});

