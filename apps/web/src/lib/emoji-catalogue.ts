/** Case-insensitive search across every category, by name. */
export const searchEmoji = (query: string): CatalogueEmoji[] => {
	const q = query.trim().toLowerCase();
	if (q === "") return [];
	return EMOJI_CATEGORIES.flatMap((c) =>
		c.emoji.filter((e) => e.name.includes(q)),
	);
};
